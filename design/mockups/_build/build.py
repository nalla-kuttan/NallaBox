"""Build the NallaBox mockups: screens.js, index.html and every registered screen page.

Run: python3 design/mockups/_build/build.py
Pages are generated; edit the page functions in this folder, not the HTML output.
"""
import html
import importlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))

from manifest import entries  # noqa: E402
import kit  # noqa: E402

PAGE_MODULES = ["pages_tv", "pages_phone", "pages_redacted", "pages_sketch", "pages_insider", "pages_host_iphone", "pages_host_mac"]


def write_manifest(items):
    js = "/* Generated by _build/build.py — screen manifest (JSON array). */\nwindow.NB_SCREENS = " + json.dumps(items, indent=1, ensure_ascii=False) + ";\n"
    (ROOT / "shared" / "screens.js").write_text(js)


def write_index(items):
    groups = []
    for g in ("Shell", "Redacted", "Composite Sketch", "Insider Trading", "iPhone host", "Mac host"):
        cards = "".join(
            f'<a class="idx-card" href="{e["path"]}"><span class="idx-id">{html.escape(e["id"])}</span>'
            f'<span class="idx-title">{html.escape(e["title"])}</span><span class="idx-surface">{e["surface"]}</span></a>'
            for e in items if e["group"] == g)
        groups.append(f'<section><h2>{g}</h2><div class="idx-grid">{cards}</div></section>')
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>NallaBox mockups</title>
<link rel="stylesheet" href="shared/tokens.css"><link rel="stylesheet" href="shared/base.css">
<style>
 body {{ background: var(--nb-color-ink); padding: 40px 32px 80px; max-width: 1280px; margin: 0 auto; }}
 header {{ display: flex; align-items: center; gap: 16px; margin-bottom: 8px; }}
 header img {{ width: 56px; height: 56px; }}
 h1 {{ font-size: 40px; font-weight: 900; }}
 .lede {{ color: var(--nb-color-text-dim); font-weight: 700; margin: 0 0 24px; max-width: 760px; line-height: 1.45; }}
 .lede a {{ color: var(--nb-color-coral); }}
 h2 {{ font-size: 22px; font-weight: 900; margin: 36px 0 12px; }}
 .idx-grid {{ display: grid; grid-template-columns: repeat(auto-fill, minmax(200px, 1fr)); gap: 10px; }}
 .idx-card {{ display: grid; grid-template-columns: auto 1fr; gap: 2px 10px; align-items: baseline; padding: 12px 14px;
   background: var(--nb-color-ink-raised); border-radius: var(--nb-radius-md); color: #fff; text-decoration: none; }}
 .idx-card:hover {{ outline: 2px solid var(--nb-color-coral); }}
 .idx-id {{ font-weight: 900; color: var(--nb-color-coral); grid-row: span 2; font-size: 15px; }}
 .idx-title {{ font-weight: 800; font-size: 14px; }}
 .idx-surface {{ font-weight: 700; font-size: 12px; color: var(--nb-color-text-dim); }}
</style></head>
<body>
<header><img src="shared/img/nallabox-symbol-color.svg" alt=""><h1>NallaBox mockups</h1></header>
<p class="lede">Every v1 screen at true size, in flow order. Use the bar on each screen for prev/next and to switch states.
Also: <a href="components.html">component gallery</a> · <a href="faces.html">face states</a>.
Spec: docs/2026-11-19-nallabox-ui-ux-design.md.</p>
{''.join(groups)}
</body></html>
"""
    (ROOT / "index.html").write_text(page)


def build_pages(items):
    count = 0
    for mod_name in PAGE_MODULES:
        try:
            mod = importlib.import_module(mod_name)
        except ModuleNotFoundError as e:
            if e.name == mod_name:
                continue
            raise
        for (sid, surface), fn in mod.PAGES.items():
            entry = next(e for e in items if e["id"] == sid and e["surface"] == surface)
            out = ROOT / entry["path"]
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(kit.page(entry, *fn()))
            count += 1
    return count


def main():
    items = entries()
    write_manifest(items)
    write_index(items)
    import gallery
    (ROOT / "components.html").write_text(gallery.build())
    try:
        import faces
        (ROOT / "faces.html").write_text(faces.build())
    except ModuleNotFoundError as e:
        if e.name != "faces":
            raise
    n = build_pages(items)
    print(f"manifest {len(items)} screens · pages written {n}")


if __name__ == "__main__":
    main()
